export const getDailyPrompt = (dateStr: string): string | undefined => {
	if (DAILY_PROMPTS.length === 0) return undefined;
	const hash = dateStr.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
	return DAILY_PROMPTS[hash % DAILY_PROMPTS.length];
};
